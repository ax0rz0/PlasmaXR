#!/usr/bin/env python3
"""Generates app/src/main/cpp/wayland/protocol_gen.{h,cpp} from the protocol XML in ./protocols.

The compositor speaks the Wayland wire protocol directly (no libwayland), so it needs, for every
interface, the signature of each request and event and the opcode numbers. They are taken from
the official XML rather than written by hand.

    python3 tools/wayland/gen.py
"""
import os
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
PROTO = os.path.join(HERE, "protocols")
OUT = os.path.join(HERE, "..", "..", "app", "src", "main", "cpp", "wayland")
FILES = ["wayland.xml", "xdg-shell.xml", "xdg-decoration-unstable-v1.xml", "viewporter.xml"]

TYPE = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o", "new_id": "n",
        "array": "a", "fd": "h"}
KEYWORDS = {"default", "delete", "new", "class", "switch", "register", "export", "long", "short",
            "union", "enum", "namespace", "template", "this", "operator", "private", "public"}


def ident(name):
    name = name.replace("-", "_")
    if name[0].isdigit():
        name = "k" + name
    return name + "_" if name in KEYWORDS else name


def signature(msg):
    sig = ""
    for a in msg.findall("arg"):
        t = a.get("type")
        if t == "new_id" and a.get("interface") is None:
            sig += "N"  # untyped new_id: interface string, version, id
            continue
        if a.get("allow-null") == "true":
            sig += "?"
        sig += TYPE[t]
    return sig


def new_iface(msg):
    for a in msg.findall("arg"):
        if a.get("type") == "new_id" and a.get("interface"):
            return a.get("interface")
    return None


def main():
    interfaces = []
    for f in FILES:
        root = ET.parse(os.path.join(PROTO, f)).getroot()
        for itf in root.findall("interface"):
            interfaces.append(itf)

    cpp = ['// GENERATED by tools/wayland/gen.py from tools/wayland/protocols/*.xml. Do not edit.',
           '#include "wayland/protocol_gen.h"', '', '#include <cstring>', '', 'namespace pxr {',
           'namespace wl {', '']
    hdr = ['// GENERATED by tools/wayland/gen.py from tools/wayland/protocols/*.xml. Do not edit.',
           '#pragma once', '', '#include <cstdint>', '', '#include "wayland/wire.h"', '',
           'namespace pxr {', 'namespace wl {', '']

    table = []
    for itf in interfaces:
        name = itf.get("name")
        reqs = itf.findall("request")
        evts = itf.findall("event")

        def emit(kind, msgs):
            if not msgs:
                return "nullptr"
            var = f"{name}_{kind}"
            cpp.append(f"static const Message {var}[] = {{")
            for m in msgs:
                ni = new_iface(m)
                cpp.append('    {"%s", "%s", %s, %d, %s},' % (
                    m.get("name"), signature(m), m.get("since", "1"),
                    1 if m.get("type") == "destructor" else 0,
                    '"%s"' % ni if ni else "nullptr"))
            cpp.append("};")
            return var

        rv = emit("req", reqs)
        ev = emit("evt", evts)
        table.append('    {"%s", %s, %s, %d, %s, %d},' % (name, itf.get("version"), rv, len(reqs), ev, len(evts)))

        # Opcode enums and protocol enums.
        hdr.append(f"namespace {name} {{")
        hdr.append("enum Req : uint16_t { %s };" % ", ".join(ident(m.get("name")) for m in reqs))
        hdr.append("enum Evt : uint16_t { %s };" % ", ".join(ident(m.get("name")) for m in evts))
        for en in itf.findall("enum"):
            entries = ", ".join(f"{ident(e.get('name'))} = {int(e.get('value'), 0)}u"
                                for e in en.findall("entry"))
            hdr.append("struct %s_ { enum : uint32_t { %s }; };" % (ident(en.get("name")), entries))
        hdr.append("constexpr uint32_t kVersion = %s;" % itf.get("version"))
        hdr.append(f"}}  // namespace {name}")
        hdr.append("")

    cpp.append("")
    cpp.append("const Interface kInterfaces[] = {")
    cpp.extend(table)
    cpp.append("};")
    cpp.append(f"const int kInterfaceCount = {len(table)};")
    cpp.append("")
    cpp.append("const Interface* findInterface(const char* name) {")
    cpp.append("    for (int i = 0; i < kInterfaceCount; ++i) {")
    cpp.append("        if (strcmp(kInterfaces[i].name, name) == 0) return &kInterfaces[i];")
    cpp.append("    }")
    cpp.append("    return nullptr;")
    cpp.append("}")
    cpp.append("")
    cpp.append("}  // namespace wl")
    cpp.append("}  // namespace pxr")
    hdr.append("extern const Interface kInterfaces[];")
    hdr.append("extern const int kInterfaceCount;")
    hdr.append("const Interface* findInterface(const char* name);")
    hdr.append("")
    hdr.append("}  // namespace wl")
    hdr.append("}  // namespace pxr")

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "protocol_gen.cpp"), "w") as f:
        f.write("\n".join(cpp) + "\n")
    with open(os.path.join(OUT, "protocol_gen.h"), "w") as f:
        f.write("\n".join(hdr) + "\n")
    # The keymap clients are told to use: a compiled XKB text keymap, embedded as a string.
    with open(os.path.join(PROTO, "us.xkb")) as f:
        keymap = f.read()
    assert ")XKB\"" not in keymap
    with open(os.path.join(OUT, "keymap_us.cpp"), "w") as f:
        f.write("// GENERATED by tools/wayland/gen.py from tools/wayland/protocols/us.xkb. Do not edit.\n")
        f.write("#include \"wayland/internal.h\"\n\nnamespace pxr {\nnamespace wl {\n\n")
        f.write("const char* const kKeymapUs = R\"XKB(" + keymap + ")XKB\";\n\n")
        f.write("}  // namespace wl\n}  // namespace pxr\n")
    print(f"{len(interfaces)} interfaces -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
